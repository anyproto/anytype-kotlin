/**
 * Maps a custom icon name to its drawable, for the View based screens.
 *
 * [CustomIcons] holds the same icon set for Compose, as `ImageVector` objects, and it uses the
 * same keys. A new icon needs an entry in both maps. `CustomIconDrawablesTest` checks the parity.
 *
 * Every entry names a drawable statically. This is deliberate. The release build runs
 * `shrinkResources true`, and R8 deletes a resource that no code names statically. The widget
 * built the name at run time before, with `resources.getIdentifier("ci_" + iconName, ...)`.
 * R8 cannot see such a name, so the production APK held 8 of the 389 icons, and the type icons
 * disappeared from every View based screen.
